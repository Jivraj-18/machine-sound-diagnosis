"""Bundle common.py + embed_pretrained.py into a single Kaggle script kernel (kaggle/kernel/run.py)."""
import sys
from pathlib import Path

models = sys.argv[1:]  # optional subset of models to run
root = Path(__file__).resolve().parent.parent
files = {n: (root / n).read_text() for n in ["common.py", "embed_pretrained.py"]}
(root / "kaggle" / "kernel" / "run.py").write_text(f'''# Auto-generated by kaggle/build_kernel.py -- do not edit.
import glob, subprocess, sys
from pathlib import Path
W = Path("/kaggle/working")
for name, src in {files!r}.items():
    (W / name).write_text(src)
subprocess.run("nvidia-smi; nproc; free -g", shell=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "einops", "psutil", "timm"], check=True)
# transformers 4.x side-install for FISHER only (see embed_pretrained.py)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", "--target", str(W / "tf4"),
                "transformers==4.57.1", "huggingface_hub==0.35.3", "tokenizers==0.22.1"], check=True)
import os
os.environ["FISHER_PYTHONPATH"] = str(W / "tf4")
raw = glob.glob("/kaggle/input/**/raw.npz", recursive=True)[0]
print("raw:", raw, flush=True)
subprocess.run([sys.executable, str(W / "embed_pretrained.py"), "--raw", raw, "--out", str(W / "cache")] + {(["--models"] + models) if models else []!r}, cwd=W)
subprocess.run(f"{{sys.executable}} -m pip freeze > {{W}}/cache/pip_freeze.txt", shell=True)
''')
print("wrote kaggle/kernel/run.py")
