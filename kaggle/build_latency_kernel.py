"""Bundle latency_bench.py and its imports into a Kaggle script kernel (kaggle/latency/run.py)."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
files = {n: (root / n).read_text() for n in
         ["common.py", "embed_pretrained.py", "evaluate.py", "features_handcrafted.py", "latency_bench.py"]}
(root / "kaggle" / "latency" / "run.py").write_text(f'''# Auto-generated by kaggle/build_latency_kernel.py -- do not edit.
import glob, os, subprocess, sys
from pathlib import Path
W = Path("/kaggle/working")
for name, src in {files!r}.items():
    (W / name).write_text(src)
subprocess.run("nvidia-smi -L; nproc; lscpu | grep 'Model name'", shell=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "einops", "psutil", "timm", "omegaconf"], check=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", "--target", str(W / "tf4"),
                "transformers==4.57.1", "huggingface_hub==0.35.3", "tokenizers==0.22.1"], check=True)
os.environ["FISHER_PYTHONPATH"] = str(W / "tf4")
raw = glob.glob("/kaggle/input/**/raw.npz", recursive=True)[0]
(W / "results").mkdir(exist_ok=True)
subprocess.run([sys.executable, str(W / "latency_bench.py"), "--raw", raw, "--threads", "4",
                "--host", "Kaggle 4 vCPU + T4", "--out", str(W / "latency_kaggle.csv")], cwd=W)
''')
print("wrote kaggle/latency/run.py")
